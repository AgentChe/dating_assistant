/// Чем закончилась покупка или восстановление (аналог PurchaseActionResult из Swift-проектов).
enum PurchaseResult {
  /// Пользователь закрыл окно оплаты.
  cancelled,

  /// OtterScale провалидировал чек, подписка активна.
  subscribed,

  /// Чек проверен, но активной подписки нет — например, восстанавливать нечего.
  notSubscribed,
}
